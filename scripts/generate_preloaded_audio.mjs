async function generateAudio(journeyId, lang, text) {
  const filePath = path.join(AUDIO_DIR, `${journeyId}_${lang}.wav`);
  if (fs.existsSync(filePath) && fs.statSync(filePath).size > 1000) {
    console.log(`[EXISTS] ${journeyId}_${lang}.wav`);
    return;
  }

  const langCode = LANG_MAP[lang] ?? "en-IN";
  console.log(`[GENERATING] ${journeyId}_${lang} (${langCode})...`);

  try {
    const res = await fetch("https://api.sarvam.ai/text-to-speech", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "api-subscription-key": SARVAM_API_KEY,
      },
      body: JSON.stringify({
        text,
        language_code: langCode,
        model: "bulbul:v3",
        speaker: "priya",
        pace: 0.95,
        enable_preprocessing: true,
      }),
    });

    if (!res.ok) {
      const err = await res.text();
      console.error(`[FAILED] ${journeyId}_${lang}:`, res.status, err);
      return;
    }

    const data = await res.json();
    if (data.audios && data.audios[0]) {
      const buffer = Buffer.from(data.audios[0], "base64");
      fs.writeFileSync(filePath, buffer);
      console.log(`[SAVED] ${journeyId}_${lang}.wav (${buffer.length} bytes)`);
    } else {
      console.error(`[EMPTY] ${journeyId}_${lang}: No audio returned`);
    }
  } catch (err) {
    console.error(`[ERROR] ${journeyId}_${lang}:`, err.message);
  }
}

async function run() {
  console.log("=== GENERATING 32 SARVAM BULBUL AUDIO ASSETS ===");
  const journeys = Object.keys(AUDIO_SCRIPTS);
  const languages = Object.keys(LANG_MAP);

  for (const jId of journeys) {
    for (const lang of languages) {
      const text = AUDIO_SCRIPTS[jId][lang];
      await generateAudio(jId, lang, text);
      // Brief 250ms pause to be polite to rate limits
      await new Promise((r) => setTimeout(r, 250));
    }
  }

  console.log("=== COMPLETED ALL 32 AUDIO ASSETS ===");
}

run();
